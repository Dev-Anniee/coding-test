SELECT C.CAR_ID, C.CAR_TYPE, ROUND(C.DAILY_FEE * 30 * (100 - P.DISCOUNT_RATE) / 100) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C
-- '30일 이상' 조건에 해당하는 할인율
JOIN (SELECT CAR_TYPE, DISCOUNT_RATE FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN
     WHERE DURATION_TYPE = '30일 이상') P ON C.CAR_TYPE = P.CAR_TYPE
-- 2022년 11월에 단 하루라도 대여 기록이 있는 차는 제외
WHERE C.CAR_ID NOT IN(SELECT CAR_ID 
                      FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY 
                      WHERE END_DATE >= TO_DATE('2022-11-01','YYYY-MM-DD')
                        AND TO_DATE('2022-11-30','YYYY-MM-DD') >= START_DATE)
-- 차종이 'SUV' 이거나 '세단'
AND (C.CAR_TYPE = 'SUV' OR C.CAR_TYPE = '세단')
-- 30일 대여 금액이 50만 원 이상 200만 원 미만
AND ROUND(C.DAILY_FEE * 30 * (100 - P.DISCOUNT_RATE) / 100) >= 500000 
AND ROUND(C.DAILY_FEE * 30 * (100 - P.DISCOUNT_RATE) / 100) < 2000000
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC;