SELECT B.AUTHOR_ID, A.AUTHOR_NAME, B.CATEGORY, SUM(B.PRICE*BS.SALES) AS TOTAL_SALES
FROM BOOK B
JOIN AUTHOR A USING (AUTHOR_ID)
JOIN (SELECT BOOK_ID, SUM(SALES) AS SALES FROM BOOK_SALES WHERE DATE_FORMAT(SALES_DATE,'%Y-%m') = '2022-01' GROUP BY BOOK_ID) BS USING (BOOK_ID)
GROUP BY B.AUTHOR_ID, A.AUTHOR_NAME, B.CATEGORY
ORDER BY B.AUTHOR_ID,B.CATEGORY DESC;