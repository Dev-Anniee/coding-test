SELECT EXTRACT(MONTH FROM START_DATE) MONTH, CAR_ID, COUNT(CAR_ID) AS RECORDS
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
WHERE CAR_ID IN (
    SELECT CAR_ID 
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY 
    WHERE START_DATE >= TO_DATE('2022-08', 'YYYY-MM')
    AND START_DATE < TO_DATE('2022-11', 'YYYY-MM') GROUP BY CAR_ID 
    HAVING COUNT(CAR_ID)>=5)
AND TO_DATE('202208','YYYYMM') <= START_DATE AND 
    TO_DATE('202211','YYYYMM') > START_DATE
GROUP BY EXTRACT(MONTH FROM START_DATE), CAR_ID
HAVING COUNT(CAR_ID)>0
ORDER BY MONTH, CAR_ID DESC;